<?php

declare(strict_types=1);

namespace Bitrix\Crm\V2\Internal\Service\Field\Requirement;

use Bitrix\Crm\Item;
use Bitrix\Crm\Multifield;
use Bitrix\Crm\Service\Container;
use Bitrix\Crm\Service\Factory;
use Bitrix\Crm\V2\Internal\Service\Item\CustomFieldRegistry;
use Bitrix\Crm\V2\Internal\Service\Item\FieldRegistry;
use Bitrix\Crm\V2\Public\Entity\Field\Requirement\Error;
use Bitrix\Crm\V2\Public\Entity\Field\Requirement\Exception;
use Bitrix\Crm\V2\Public\EntityType;

/**
 * @internal
 */
final class SetFieldPolicy
{
	private readonly \Closure $fieldAvailabilityChecker;

	/**
	 * @param null|\Closure(EntityType, int, string): bool $fieldAvailabilityChecker
	 */
	public function __construct(?\Closure $fieldAvailabilityChecker = null)
	{
		$this->fieldAvailabilityChecker = $fieldAvailabilityChecker
			?? static function (EntityType $entityType, int $userId, string $fieldName): bool {
				if (!str_starts_with($fieldName, 'UF_'))
				{
					return true;
				}

				return !in_array(
					$fieldName,
					CustomFieldRegistry::getInstance()->getHiddenFieldNames($entityType, $userId),
					true,
				);
			};
	}

	public function assertEligible(
		EntityType $entityType,
		int $userId,
		Context $context,
		ResolvedRequirementField $field,
	): void
	{
		$fieldName = $field->legacyRequirementFieldName;
		$factory = Container::getInstance()->getFactory($entityType->getId());
		if ($fieldName === null || $factory === null)
		{
			throw new Exception(Error::FIELD_REQUIREMENT_NOT_SUPPORTED);
		}

		$descriptor = FieldRegistry::getInstance($entityType)->getField($field->fieldId);
		if ($descriptor?->readonly === true || !($this->fieldAvailabilityChecker)($entityType, $userId, $fieldName))
		{
			throw new Exception(Error::FIELD_REQUIREMENT_NOT_SUPPORTED);
		}

		$item = $this->createItem($factory, $context);
		if ($item->isFieldDisabled($fieldName))
		{
			throw new Exception(Error::FIELD_REQUIREMENT_NOT_SUPPORTED);
		}

		$operationField = $factory->getFieldsCollection()->getField($fieldName);
		if ($operationField !== null)
		{
			if (
				!$operationField->isDisplayed()
				|| !$operationField->isValueCanBeChanged()
				|| $operationField->isAutoGenerated()
			)
			{
				throw new Exception(Error::FIELD_REQUIREMENT_NOT_SUPPORTED);
			}

			return;
		}

		if (
			isset($factory->getDependantFieldsMap()[$fieldName])
			|| (Multifield\TypeRepository::isTypeDefined($fieldName) && $item->hasField(Item::FIELD_NAME_FM))
		)
		{
			return;
		}

		throw new Exception(Error::FIELD_REQUIREMENT_NOT_SUPPORTED);
	}

	private function createItem(Factory $factory, Context $context): Item
	{
		$data = [];
		if ($factory->isCategoriesSupported() && $context->categoryId !== null)
		{
			$data[Item::FIELD_NAME_CATEGORY_ID] = $context->categoryId;
		}

		return $factory->createItem($data);
	}
}
