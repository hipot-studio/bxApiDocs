use Bitrix\Main\Localization\Loc;
use Bitrix\Main\Result;
use Bitrix\Main\Type\Collection;
use Bitrix\Main\UI\PageNavigation;

final class AutomatedSolution extends Base
{
	private UserPermissions $userPermissions;
	private AutomatedSolutionManager $manager;
	private DynamicTypesMap $dynamicTypesMap;
	private Converter\AutomatedSolution $converter;

	private ?array $importedAutomatedSolutions = null;

	protected function init(): void
	{
		parent::init();

		$this->userPermissions = Container::getInstance()->getUserPermissions();
		$this->manager = Container::getInstance()->getAutomatedSolutionManager();
		$this->dynamicTypesMap = Container::getInstance()->getDynamicTypesMap();
		$this->converter = Container::getInstance()->getAutomatedSolutionConverter();
	}

	private function checkPermissions(?int $id = null): bool
	{
		if ($this->userPermissions->automatedSolution()->canEdit($id))
		{
			return true;
		}

		if ($id !== null && CapabilityAccessChecker::getInstance()->isLockedAutomatedSolution($id))
		{
			$this->addError(
				new Error(
					Loc::getMessage('CRM_CONTROLLER_AUTOMATED_SOLUTION_IMPORTED_LOCKED'),
					ErrorCode::RESTRICTED_BY_TARIFF,
					[
						'sliderCode' => 'limit_v2_crm_automated_solution_marketplace',
					],
				),
			);
		}
		else
		{
			$this->addError(ErrorCode::getAccessDeniedError());
		}

		return false;
	}

	public function fieldsAction(): ?array
	{
		if (!$this->checkPermissions())
		{
			return null;
		}

		return $this->prepareFieldsInfo($this->getFieldsInfo());
	}

	private function getFieldsInfo(): array
	{
		$fieldsInfo = [
			'ID' => [
				'TYPE' => Field::TYPE_INTEGER,
				'ATTRIBUTES' => [\CCrmFieldInfoAttr::AutoGenerated, \CCrmFieldInfoAttr::ReadOnly],
				'NORMALIZER' => intval(...),
			],

			'TITLE' => [
				'TYPE' => Field::TYPE_STRING,
				'ATTRIBUTES' => [\CCrmFieldInfoAttr::Required, \CCrmFieldInfoAttr::CanNotBeEmptied],
				'NORMALIZER' => strval(...),
			],

			'TYPE_IDS' => [
				'TYPE' => Field::TYPE_CRM_DYNAMIC_TYPE,
				'ATTRIBUTES' => [\CCrmFieldInfoAttr::Multiple],
				'NORMALIZER' => static function (mixed $value): array {
					$array = (array)$value;

					Collection::normalizeArrayValuesByInt($array);

					return $array;
				},
			],

			'SOURCE_ID' => [
				'TYPE' => Field::TYPE_INTEGER,
				'ATTRIBUTES' => [
					\CCrmFieldInfoAttr::Hidden,
					\CCrmFieldInfoAttr::Immutable,
					\CCrmFieldInfoAttr::NotDisplayed,
					\CCrmFieldInfoAttr::HasDefaultValue,
				],
				'NORMALIZER' => intval(...),
			],

			'VIBE_ID' => [
				'TYPE' => Field::TYPE_INTEGER,
				'ATTRIBUTES' => [\CCrmFieldInfoAttr::Hidden, \CCrmFieldInfoAttr::NotDisplayed],
				'NORMALIZER' => intval(...),
			],

			'IS_VIBE_ENABLED' => [
				'TYPE' => Field::TYPE_BOOLEAN,
				'ATTRIBUTES' => [\CCrmFieldInfoAttr::Hidden, \CCrmFieldInfoAttr::NotDisplayed],
				'NORMALIZER' => AutomatedSolutionVibe::normalizeValue(...),
			],
		];

		if (!$this->isRest())
		{
			$fieldsInfo['DESCRIPTION'] = [
				'TYPE' => Field::TYPE_STRING,
				'NORMALIZER' => static fn(mixed $value): mixed => $value,
			];
		}

		return $fieldsInfo;
	}

	public function getAction(int $id): ?array
	{
		if (!$this->checkPermissions())
		{
			return null;
		}

		$solution = $this->manager->getAutomatedSolution($id);
		if (!$solution)
		{
			$this->addError(ErrorCode::getNotFoundError());

			return null;
		}

		return [
			'automatedSolution' => $this->converter->toJson($solution),
		];
	}

	public function addAction(array $fields = [], ?\CRestServer $server = null): mixed
	{
		$builder = (new CreateEvent())
			->setSection(Dictionary::SECTION_REST)
		;

		if ($this->isRest())
		{
			$builder->setSource(Dictionary::getApplicationSource($server?->getClientId()));

			$builder
				->setStatus(Dictionary::STATUS_ATTEMPT)
				->buildEvent()
				->send()
			;
		}

		$result = $this->add($fields);
		if ($result instanceof AjaxJson)
		{
			if ($this->isRest())
			{
				$builder->setStatus(Dictionary::STATUS_ERROR)->buildEvent()->send();
			}

			return $result;
		}

		if ($this->isRest())
		{
			if (isset($result['automatedSolution']['id']))
			{
				$builder->setId($result['automatedSolution']['id']);
			}
			if (isset($result['automatedSolution']['typeIds']))
			{
				$builder->setTypeIds($result['automatedSolution']['typeIds']);
			}

			if ($this->getErrors())
			{
				$builder->setStatus(Dictionary::STATUS_ERROR);
			}
			else
			{
				$builder->setStatus(Dictionary::STATUS_SUCCESS);
			}

			$builder
				->buildEvent()
				->send()
			;
		}

		return $result;
	}

	private function add(array $fields = []): mixed
	{
		if (!$this->checkPermissions())
		{
			return null;
		}

		$limitCheckResult = RestrictionManager::getAutomatedSolutionLimitRestriction()->check();
		if (!$limitCheckResult->isSuccess())
		{
			$this->addErrors($limitCheckResult->getErrors());

			return null;
		}

		$fieldsToAdd = $this->normalizeDescription($this->prepareFieldsFromRequest($fields));
		if ($fieldsToAdd === null)
		{
			return null;
		}

		if (!$this->checkAccessToTypeIds($fieldsToAdd['TYPE_IDS'] ?? []))
		{
			return null;
		}

		$addResult = $this->manager->addAutomatedSolution($fieldsToAdd);
		if (!$addResult->isSuccess())
		{
			if (isset($addResult->getData()['fields']['ID']))
			{
				return $this->createLifecycleErrorResponse($addResult);
			}

			$this->addErrors($addResult->getErrors());

			return null;
		}

		$solutionId = $addResult->getData()['fields']['ID'];

		$setTypesResult = $this->setTypes($solutionId, $fieldsToAdd['TYPE_IDS'] ?? []);
		if (!$setTypesResult->isSuccess())
		{
			$this->addErrors($setTypesResult->getErrors());
		}

		return $this->getAction($solutionId);
	}

	public function updateAction(int $id, array $fields = []): mixed
	{
		$builder = (new EditEvent())
			->setSection(Dictionary::SECTION_REST)
			->setId($id)
		;

		if ($this->isRest())
		{
			$builder
				->setStatus(Dictionary::STATUS_ATTEMPT)
				->buildEvent()
				->send()
			;
		}

		$result = $this->update($id, $fields);
		if ($result instanceof AjaxJson)
		{
			if ($this->isRest())
			{
				$builder->setStatus(Dictionary::STATUS_ERROR)->buildEvent()->send();
			}

			return $result;
		}

		if ($this->isRest())
		{
			if (isset($result['automatedSolution']['typeIds']))
			{
				$builder->setTypeIds($result['automatedSolution']['typeIds']);
			}

			if ($this->getErrors())
			{
				$builder->setStatus(Dictionary::STATUS_ERROR);
			}
			else
			{
				$builder->setStatus(Dictionary::STATUS_SUCCESS);
			}

			$builder
				->buildEvent()
				->send()
			;
		}

		return $result;
	}

	private function update(int $id, array $fields = []): mixed
	{
		if (!$this->checkPermissions($id))
		{
			return null;
		}

		$currentAutomatedSolutionResponse = $this->getAction($id);
		if (!is_array($currentAutomatedSolutionResponse) || !empty($this->getErrors()))
		{
			return null;
		}

		// fill not provided fields with current values. we don't want unprovided fields to change
		$fieldsToUpdate = $this->normalizeDescription(
			$this->prepareFieldsFromRequest($fields + $currentAutomatedSolutionResponse['automatedSolution']),
		);
		if ($fieldsToUpdate === null)
		{
			return null;
		}

		$typeIds = array_map('intval', $fieldsToUpdate['TYPE_IDS'] ?? []);

		$currentTypeIds = $currentAutomatedSolutionResponse['automatedSolution']['typeIds'] ?? [];
		$currentTypeIds = array_map('intval', $currentTypeIds);

		if (!$this->checkAccessToTypeIds($typeIds, $currentTypeIds, $id))
		{
			return null;
		}

		$updateResult = $this->manager->updateAutomatedSolution($id, $fieldsToUpdate);
		if (!$updateResult->isSuccess())
		{
			if (isset($updateResult->getData()['fields']['ID']))
			{
				return $this->createLifecycleErrorResponse($updateResult);
			}

			$this->addErrors($updateResult->getErrors());
		}

		$setTypesResult = $this->setTypes($id, $fieldsToUpdate['TYPE_IDS'] ?? []);
		if (!$setTypesResult->isSuccess())
		{
			$this->addErrors($setTypesResult->getErrors());
		}

		return $this->getAction($id);
	}

	private function createLifecycleErrorResponse(Result $result): AjaxJson
	{
		$this->addErrors($result->getErrors());

		$fields = $result->getData()['fields'];

		return AjaxJson::createError(
			$result->getErrorCollection(),
			[
				'automatedSolution' => [
					'id' => (int)$fields['ID'],
					'title' => (string)$fields['TITLE'],
					'typeIds' => array_map('intval', (array)($fields['TYPE_IDS'] ?? [])),
					'vibeId' => (int)($fields['VIBE_ID'] ?? 0),
					'isVibeEnabled' => AutomatedSolutionVibe::isEnabledForAutomatedSolution($fields),
				],
			],
		);
	}

	public function deleteAction(int $id): void
	{
		$analyticsBuilder = (new DeleteEvent())
			->setSection(Dictionary::SECTION_REST)
			->setId($id)
		;

		if ($this->isRest())
		{
			$analyticsBuilder
				->setStatus(Dictionary::STATUS_ATTEMPT)
				->buildEvent()
				->send()
			;
		}

		$this->delete($id);

		if ($this->isRest())
		{
			if ($this->getErrors())
			{
				$analyticsBuilder->setStatus(Dictionary::STATUS_ERROR);
			}
			else
			{
				$analyticsBuilder->setStatus(Dictionary::STATUS_SUCCESS);
			}

			$analyticsBuilder
				->buildEvent()
				->send()
			;
		}
	}

	private function delete(int $id): void
	{
		if (!$this->checkPermissions($id))
		{
			return;
		}

		$deleteResult = $this->manager->deleteAutomatedSolution($id);

		if (!$deleteResult->isSuccess())
		{
			$this->addErrors($deleteResult->getErrors());
		}
	}

	/**
	 * @param array $fields
	 *
	 * @return array filtered and normalized SNAKE_CASE fields
	 */
	private function prepareFieldsFromRequest(array $fields): array
	{
		$snakeFields = $this->convertKeysToUpper($fields);

		$filteredFields = $this->filterOutUnknownFields($snakeFields);

		return $this->normalizeFieldValues($filteredFields);
	}

	private function filterOutUnknownFields(array $snakeCaseFields): array
	{
		if ($this->isRest())
		{
			unset($snakeCaseFields['IS_VIBE_ENABLED'], $snakeCaseFields['DESCRIPTION']);
		}

		$knownFields = array_keys($this->getFieldsInfo());

		return array_filter(
			$snakeCaseFields,
			fn(mixed $key) => in_array($key, $knownFields, true),
			ARRAY_FILTER_USE_KEY,
		);
	}

	private function normalizeFieldValues(array $snakeCaseFields): array
	{
		$result = [];
		foreach ($snakeCaseFields as $fieldName => $value)
		{
			$normalizer = $this->getFieldsInfo()[$fieldName]['NORMALIZER'];

			$result[$fieldName] = $normalizer($value);
		}

		return $result;
	}

	private function normalizeDescription(array $snakeCaseFields): ?array
	{
		if (!array_key_exists('DESCRIPTION', $snakeCaseFields))
		{
			return $snakeCaseFields;
		}

		$result = (new DescriptionNormalizer())->normalize($snakeCaseFields['DESCRIPTION']);
		if (!$result->isSuccess())
		{
			$this->addErrors($result->getErrors());

			return null;
		}

		$snakeCaseFields['DESCRIPTION'] = $result->getData()['description'];

		return $snakeCaseFields;
	}

	private function setTypes(int $automatedSolutionId, array $typeIds): Result
	{
		$this->dynamicTypesMap->load([
			'isLoadStages' => false,
			'isLoadCategories' => false,
		]);

		$types = $this->dynamicTypesMap->getBunchOfTypesByIds($typeIds);

		return $this->manager->setTypeBindingsInAutomatedSolution(
			$types,
			$automatedSolutionId,
		);
	}

	public function listAction(?array $order = null, ?array $filter = null, ?PageNavigation $pageNavigation = null): ?Page
	{
		if (!$this->checkPermissions())
		{
			return null;
		}

		$order ??= ['id' => 'ASC'];
		if (!$this->validateOrder($order, ['id', 'title']))
		{
			return null;
		}

		$filter ??= [];
		if (!$this->validateFilter($filter, ['id', 'title']))
		{
			return null;
		}

		$snakeCaseOrder = $this->convertKeysToUpper($order);
		$snakeCaseFilter = $this->convertKeysToUpper($filter);

		$action = new Fetch(
			$snakeCaseFilter,
			$snakeCaseOrder,
			$pageNavigation?->getOffset(),
			$pageNavigation?->getLimit(),
		);

		$result = $action->execute();
		if (!$result->isSuccess())
		{
			$this->addErrors($result->getErrors());

			return null;
		}

		$solutions = $result->getData()['automatedSolutions'] ?? [];

		return new Page(
			'automatedSolutions',
			array_map($this->converter->toJson(...), $solutions),
			fn() => AutomatedSolutionTable::getCount($snakeCaseFilter),
		);
	}

	public function getVibeSettingsAction(int $automatedSolutionId): ?Component
	{
		if (!$this->checkPermissions($automatedSolutionId))
		{
			return null;
		}

		if (!Feature::enabled(AutomatedSolutionVibe::class) || !VibeRepository::isVibeAvailable())
		{
			$this->addVibeSettingsUnavailableError();

			return null;
		}

		$automatedSolution = $this->manager->getAutomatedSolution($automatedSolutionId);
		if (
			$automatedSolution === null
			|| (int)($automatedSolution['VIBE_ID'] ?? 0) <= 0
		)
		{
			$this->addVibeSettingsUnavailableError();

			return null;
		}

		$vibe = Container::getInstance()
			->getVibeRepository()
			?->findById((int)$automatedSolution['VIBE_ID'])
		;
		if ($vibe === null)
		{
			$this->addVibeSettingsUnavailableError();

			return null;
		}

		return $this->renderComponentAjax(
			'bitrix:crm.automated_solution.start.settings',
			'',
			[
				'automatedSolutionId' => $automatedSolutionId,
			],
		);
	}

	private function addVibeSettingsUnavailableError(): void
	{
		$this->addError(new Error('Vibe settings are unavailable.', 'VIBE_SETTINGS_UNAVAILABLE'));
	}

	private function checkAccessToTypeIds(array $typeIds, array $currentTypeIds = [], ?int $targetAutomatedSolutionId = null): bool
	{
		$this->dynamicTypesMap->load([
			'isLoadStages' => false,
			'isLoadCategories' => false,
		]);

		$types = $this->dynamicTypesMap->getBunchOfTypesByIds(array_unique([...$typeIds, ...$currentTypeIds]));

		foreach ($types as $type)
		{
			$hasPermission = false;

			$automatedSolutionId = $type->getCustomSectionId();
			if ($automatedSolutionId)
			{
				if ($this->isTypeBoundToImportedAutomatedSolution($type))
				{
					if (
						$targetAutomatedSolutionId === null
						|| $type->getCustomSectionId() !== $targetAutomatedSolutionId
						|| (in_array($type->getId(), $currentTypeIds, true) && !in_array($type->getId(), $typeIds, true))
					)
					{
						$this->addError(new Error(Loc::getMessage('CRM_CONTROLLER_AUTOMATED_SOLUTION_DRAFT_LOCKED')));

						return false;
					}
				}

				$hasPermission = $this->userPermissions->automatedSolution()->canEdit($automatedSolutionId);
			}
			else
			{
				$hasPermission = $this->userPermissions->isCrmAdmin();
			}

			if (!$hasPermission)
			{
				$this->addError(ErrorCode::getAccessDeniedError());

				return false;
			}
		}

		return true;
	}

	private function isTypeBoundToImportedAutomatedSolution(\Bitrix\Crm\Model\Dynamic\Type $type): bool
	{
		$customSectionId = $type->getCustomSectionId();

		foreach ($this->getImportedAutomatedSolutions() as $automatedSolution)
		{
			if ($automatedSolution['ID'] === $customSectionId)
			{
				return true;
			}
		}

		return false;
	}

	private function getImportedAutomatedSolutions(): array
	{
		if ($this->importedAutomatedSolutions === null)
		{
			$this->importedAutomatedSolutions = Container::getInstance()->getAutomatedSolutionManager()->getExistingAutomatedSolutions(AutomatedSolutionTable::SOURCE_MARKETPLACE);
		}

		return $this->importedAutomatedSolutions;
	}
}
